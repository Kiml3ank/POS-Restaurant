import "server-only";

import { headers } from "next/headers";

/**
 * IP ของเครื่องที่ยิง request เข้ามา — สำหรับ `AuditLog.ipAddress` (บทที่ 13)
 *
 * ── ทำไมต้องเก็บ ──────────────────────────────────────────────────────
 * คำถามที่ต้องตอบได้ตอนสืบสวนคือ **"กดจากเครื่องในร้าน หรือจากข้างนอก"**
 * บิลที่ถูกยกเลิกตอนตีสองจากไอพีที่ไม่เคยเห็น เป็นคนละเรื่องกับบิลที่ถูกยกเลิก
 * จากแท็บเล็ตหน้าเคาน์เตอร์ — โดยที่ทั้งสองกรณี staffId เดียวกัน
 *
 * ── เก็บแค่ IP ไม่เก็บ user-agent โดยตั้งใจ ─────────────────────────────
 * UA ไม่ได้ตอบคำถามข้างบนเพิ่ม (เครื่องในร้านเป็นรุ่นเดียวกันหมด) แต่เป็นข้อมูล
 * ที่ระบุตัวบุคคลได้ละเอียดขึ้น — เก็บเท่าที่ตอบคำถามได้ ไม่เก็บเผื่อ
 *
 * ── null ได้เสมอ และนั่นไม่ใช่ error ────────────────────────────────────
 * เรียกจากที่ที่ไม่มี request context (สคริปต์ smoke, seed) จะได้ null
 * **ห้ามให้การเขียน log ล้มเหลวเพราะอ่าน IP ไม่ได้** — log ที่หายเพราะเรื่องนี้
 * แย่กว่า log ที่ไม่มีช่อง IP
 */
export async function clientIp(): Promise<string | null> {
  try {
    const store = await headers();

    /**
     * `x-forwarded-for` เป็นรายการคั่นด้วยจุลภาค ตัวแรกคือ client จริง
     * ที่เหลือคือ proxy ที่ผ่านมา — Vercel และ reverse proxy ส่วนใหญ่ตั้งค่านี้ให้
     *
     * ⚠ header นี้ **ปลอมได้** ถ้าแอปเปิดรับ request ตรงจากอินเทอร์เน็ตโดยไม่มี
     * proxy ที่เขียนทับค่านี้ให้ — ตอน deploy จริงต้องแน่ใจว่ามี proxy อยู่ข้างหน้า
     * ไม่งั้นค่าที่เก็บได้เชื่อถือไม่ได้ในเชิงนิติวิทยาศาสตร์ (แต่ยังมีประโยชน์กว่าไม่มี)
     */
    const forwarded = store.get("x-forwarded-for");
    if (forwarded) {
      const first = forwarded.split(",")[0]?.trim();
      if (first) return first.slice(0, 45); // IPv6 ยาวสุด 45 ตัวอักษร
    }

    const real = store.get("x-real-ip")?.trim();
    return real ? real.slice(0, 45) : null;
  } catch {
    // ไม่มี request context (สคริปต์ / seed) — ไม่ใช่ error
    return null;
  }
}
