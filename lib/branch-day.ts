/**
 * "วันของสาขา" ในรูปแบบ YYYYMMDD
 *
 * ── ทำไมต้องเป็นวันของสาขา ไม่ใช่ของเครื่อง server ────────────────────────
 * ร้านที่ปิดตีสองต้องได้เลขชุดเดียวกันทั้งกะ และ server อาจรันอยู่คนละ region
 * กับร้าน (Vercel — บทที่ 16) ถ้าใช้วันของเครื่อง ออร์เดอร์ที่สั่งตอนตีหนึ่ง
 * จะไปนับเป็นวันใหม่ทั้งที่พนักงานยังอยู่ในกะเดิม แล้วรายงานปิดกะจะไม่ตรง
 *
 * ── ทำไมแยกเป็นไฟล์ ────────────────────────────────────────────────────
 * ตอนนี้มีสองตัวนับที่ต้องใช้ "วันของสาขา" ชุดเดียวกันเป๊ะ ๆ:
 *   - `Order.orderNumber` (บทที่ 7) — "YYYYMMDD-NNNN"
 *   - `TableSession.queueDay` + `queueNumber` (เลขคิวซื้อกลับ)
 * ถ้าสองที่คำนวณวันคนละแบบ จะเกิดเคสที่ออร์เดอร์เลข 20260824-0001 มีเลขคิว
 * ของวันที่ 23 ติดอยู่ ซึ่งไล่ย้อนตอนปิดกะแล้วอธิบายไม่ได้เลย
 *
 * ไม่มี `import "server-only"` เพราะหน้าจอต้องใช้เทียบว่า "คิวของวันนี้หรือเมื่อวาน"
 */

/**
 * แปลงเวลาเป็นวันของ timezone ที่ระบุ คืนเป็น "YYYYMMDD"
 *
 * ใช้ `en-CA` เพราะเป็น locale ที่ `Intl.DateTimeFormat` ให้ผลเป็น YYYY-MM-DD
 * ตรง ๆ ไม่ต้องประกอบเอง (ท่าเดียวกับที่ `nextOrderNumber()` ใช้มาตั้งแต่บทที่ 7)
 *
 * @param timezone IANA timezone ของสาขา เช่น "Asia/Bangkok"
 * @param at เวลาที่ต้องการแปลง — ค่าเริ่มต้นคือตอนนี้ (รับเข้ามาได้เพื่อให้ทดสอบได้)
 */
export function branchDayKey(timezone: string, at: Date = new Date()): string {
  return new Intl.DateTimeFormat("en-CA", { timeZone: timezone }).format(at).replaceAll("-", "");
}
