/**
 * data contract ของ event ที่ไหลผ่าน SSE (บทที่ 8)
 *
 * ไฟล์นี้ **ไม่มี `import "server-only"`** เพราะทั้งฝั่งที่ publish (lib/server/*)
 * และฝั่งที่ subscribe (client component ที่ถือ EventSource) ต้องใช้ชนิดเดียวกัน
 * ถ้าสองฝั่งประกาศชนิดแยกกันเมื่อไหร่ จะเพี้ยนออกจากกันแบบที่ tsc จับไม่ได้
 *
 * ── กฎข้อเดียวที่สำคัญที่สุดของไฟล์นี้ ─────────────────────────────────────
 * **event เป็นแค่ "สัญญาณให้ไปโหลดใหม่" ห้ามแบกข้อมูลบิล/ราคา/ชื่อเมนูมาด้วย**
 *
 * เหตุผล: ถ้าใส่ข้อมูลจริงลงไปใน event เราจะมีทางเข้าถึงข้อมูลสองทาง
 * (ทาง RSC ที่ตรวจสิทธิ์แล้ว กับทาง SSE ที่ต้องมาตรวจสิทธิ์ซ้ำเอง) แล้ววันหนึ่ง
 * สองทางนั้นจะกรองไม่เหมือนกัน — ลูกค้าโต๊ะ A จะได้เห็นของโต๊ะ B
 * ตอนนี้ทุกหน้าจอจึงรับ event แล้วสั่ง router.refresh() ให้ RSC ไปดึงของใหม่
 * ผ่านด่านสิทธิ์เดิมทุกครั้ง ข้อมูลมีทางเข้าออกทางเดียวเสมอ
 *
 * ราคาที่จ่าย: หนึ่ง event = หนึ่งรอบ render ฝั่ง server ซึ่งแพงกว่า push JSON
 * ก้อนเล็ก ๆ แต่ปริมาณของหน้าร้านหนึ่งสาขาคือหลักสิบ event ต่อนาที ไม่ใช่หลักพัน
 * ถ้าวันหนึ่งไม่พอค่อยเปลี่ยนเฉพาะจอครัวเป็น push ข้อมูลจริง
 */

/** เวอร์ชันของรูปแบบ payload — client ที่ค้างอยู่ข้ามการ deploy จะได้รู้ว่าอ่านไม่ออก */
export const REALTIME_EVENT_VERSION = 1;

/** ชื่อ event ที่ใช้ในบรรทัด `event:` ของ SSE (ฝั่ง client ผูก listener ด้วยชื่อนี้) */
export const REALTIME_SSE_EVENT = "pos-change";

export type RealtimeEventType =
  /** ตะกร้าเปลี่ยน (เพิ่ม/ลด/ลบรายการ) — ยังไม่เข้าครัว */
  | "cart.changed"
  /** ตะกร้าถูกส่งเข้าครัว DRAFT → PLACED */
  | "order.placed"
  /** ครัวกดเปลี่ยนสถานะรายการ (หรือพนักงานกดเสิร์ฟแล้ว) */
  | "order_item.status"
  /** รายการถูกยกเลิกโดยพนักงาน */
  | "order_item.cancelled"
  /** เปิด/ปิดรอบโต๊ะ */
  | "table_session.changed"
  /**
   * บิลถูกปิดด้วยการรับเงิน (บทที่ 11) — โต๊ะกลับเป็นว่างแล้ว
   *
   * แยกจาก `table_session.changed` ทั้งที่รอบโต๊ะก็ถูกปิดไปพร้อมกัน เพราะ
   * "โต๊ะว่างแล้วเพราะจ่ายเงินเรียบร้อย" กับ "โต๊ะว่างแล้วเพราะพนักงานยกเลิกรอบทิ้ง"
   * เป็นคนละเหตุการณ์ในสายตาของรายงานบทที่ 15 และของจอที่อาจอยากขึ้นข้อความต่างกัน
   * — ตอนนี้ทุกจอปฏิบัติเหมือนกันคือ refresh แต่ค่านี้แยกไว้ตั้งแต่ต้นจะถูกกว่า
   * มาแยกทีหลังตอนที่มีจอสี่จอผูกกับ event เดิมอยู่แล้ว
   */
  | "payment.completed"
  /**
   * เมนู/หมวด/กลุ่มตัวเลือกถูกแก้จากหลังร้าน (โมดูล 04)
   *
   * เคสที่ต้องมี event นี้: ครัวกด "ของหมด" ตอนสองทุ่ม แต่ลูกค้าโต๊ะ 5 เปิดหน้าเมนู
   * ค้างไว้ตั้งแต่ทุ่มครึ่ง — ถ้าไม่มีสัญญาณ เขาจะยังเห็นเมนูนั้นและกดสั่ง
   * (`addToCart()` กันไว้อีกชั้นอยู่แล้ว แต่การกดแล้วเจอ error คือประสบการณ์
   *  ที่แย่กว่าการไม่เห็นของที่หมดไปแล้วตั้งแต่แรก)
   *
   * `tableId: null` เสมอ เพราะเป็นเรื่องระดับสาขา ไม่ผูกโต๊ะใดโต๊ะหนึ่ง
   */
  | "menu.changed";

export type RealtimeEvent = {
  v: typeof REALTIME_EVENT_VERSION;
  type: RealtimeEventType;
  /** ขอบเขตของ event — subscriber ทุกตัวถูกผูกกับสาขาเดียวเสมอ */
  branchId: string;
  /**
   * โต๊ะที่เกี่ยวข้อง — ใช้กรองก่อนส่งให้ "ลูกค้า" เท่านั้น
   * (มือถือลูกค้าโต๊ะ A ต้องไม่ได้รับ event ของโต๊ะ B แม้จะเป็นแค่สัญญาณเปล่า
   *  เพราะนับจำนวน event ที่ได้รับก็พอเดาได้แล้วว่าร้านคึกแค่ไหน/โต๊ะไหนสั่งบ่อย)
   * null = event ระดับสาขาที่ไม่ผูกโต๊ะ
   */
  tableId: string | null;
  /** epoch milliseconds ตอนที่เกิดเหตุ */
  at: number;
};

/**
 * event ระดับสาขาที่ "ลูกค้าได้รับด้วย" ทั้งที่ไม่ผูกกับโต๊ะของตัวเอง
 *
 * ── ทำไมต้องมีรายชื่อนี้ ─────────────────────────────────────────────────
 * ปกติ SSE กรองให้ลูกค้าเห็นเฉพาะ event ที่ `tableId` ตรงกับโต๊ะตัวเอง (ดูเหตุผล
 * ที่ `tableId` ด้านบน) ซึ่งแปลว่า event ที่ `tableId = null` **จะไม่ถึงลูกค้าเลย**
 * — กฎนั้นถูกสำหรับทุก event ที่ผ่านมา เพราะทุกตัวเป็นเรื่องของโต๊ะใดโต๊ะหนึ่ง
 *
 * แต่ `menu.changed` เป็นเรื่องของ "เมนูร้าน" ซึ่งเป็นข้อมูลสาธารณะที่ลูกค้าทุกคน
 * เห็นอยู่แล้วบนหน้าเมนู การส่งให้ทุกโต๊ะจึงไม่รั่วอะไรเลย
 *
 * ประกาศเป็นรายชื่อแบบ opt-in ไม่ใช่เปลี่ยนกฎเป็น "ปล่อย tableId = null ทุกตัว"
 * เพราะวันหนึ่งจะมี event ระดับสาขาที่ลูกค้าไม่ควรเห็น (เช่น "ปิดกะแล้ว" ของบทที่ 15
 * ที่บอกได้ว่าร้านทำยอดเท่าไหร่) — ค่าเริ่มต้นต้องเป็น "ไม่ส่ง" เสมอ
 */
export const CUSTOMER_BROADCAST_EVENTS: readonly RealtimeEventType[] = ["menu.changed"];

/** true เมื่อ payload ที่รับมาหน้าตาเป็น RealtimeEvent รุ่นที่เรารู้จัก */
export function isRealtimeEvent(value: unknown): value is RealtimeEvent {
  if (typeof value !== "object" || value === null) {
    return false;
  }

  const event = value as Partial<RealtimeEvent>;

  return (
    event.v === REALTIME_EVENT_VERSION &&
    typeof event.type === "string" &&
    typeof event.branchId === "string" &&
    typeof event.at === "number"
  );
}
