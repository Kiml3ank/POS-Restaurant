/**
 * เลขที่ออร์เดอร์ที่ "คนอ่าน" กับเลขที่ "ฐานข้อมูลเก็บ" — คนละอย่างกันโดยตั้งใจ
 *
 * ── สิ่งที่เก็บ ──────────────────────────────────────────────────────────
 * `Order.orderNumber` = `YYYYMMDD-NNNN` ต่อสาขา (เช่น `20260824-0007`)
 * เลขวันติดมาด้วยเพราะเป็นตัวที่ทำให้ `@@unique([branchId, orderNumber])` กัน
 * เลขซ้ำข้ามวันได้ และทำให้รายงานย้อนหลังเรียง/กรองตามวันได้จากคอลัมน์เดียว
 *
 * ── สิ่งที่คนอ่าน ───────────────────────────────────────────────────────
 * พนักงานกับลูกค้าพูดถึงบิลว่า **"บิลที่ 7"** ไม่มีใครอ่านเลข 13 หลักออกเสียง
 * และตัวเลขที่ยาวเกินความจำเป็นทำให้ตัวที่ต่างกันจริง (สี่หลักท้าย) อ่านพลาดง่าย
 * — จอทุกจอจึงต้องแสดงผ่าน `dailyOrderNumber()` ไม่ใช่พิมพ์ค่าดิบออกไป
 *
 * ตัวเลขนี้ **เริ่มที่ 1 ใหม่ทุกวันตามเวลาของสาขา** (เพราะ prefix เปลี่ยนตามวัน)
 * ซึ่งเป็นพฤติกรรมที่ตั้งใจ ไม่ใช่ผลข้างเคียง — คนละเรื่องกับเลขที่ใบกำกับภาษี
 * ที่ต้องเดินต่อเนื่องตลอดกาลห้ามรีเซ็ต (ดู `DocumentCounter` ในบทที่ 12)
 *
 * ไม่มี `import "server-only"` เพราะ client component ต้องใช้แสดงผลด้วย
 */

/** รูปแบบที่ `nextOrderNumber()` ใน lib/server/cart.ts ออกให้ */
const ORDER_NUMBER_PATTERN = /^(\d{8})-(\d+)$/;

/**
 * เลขที่อ่านออกเสียงได้ของบิลใบหนึ่ง — "20260824-0007" → "7"
 *
 * **ค่าที่ไม่ตรงรูปแบบคืนกลับไปทั้งก้อน ไม่ใช่คืนค่าว่างหรือขีด** ด้วยเหตุผล
 * เดียวกับ `auditActionLabel()`: แถวที่หายไปจากหน้าจอเพราะโค้ดยังไม่รู้จักรูปแบบ
 * แย่กว่าแถวที่อ่านยาก — คนที่กำลังตามหาบิลอยู่จะสรุปว่าไม่มีบิลนั้น ซึ่งผิด
 */
export function dailyOrderNumber(orderNumber: string): string {
  const match = ORDER_NUMBER_PATTERN.exec(orderNumber);

  if (!match) {
    return orderNumber;
  }

  // ตัดศูนย์นำหน้าทิ้ง ("0007" → "7") — ศูนย์พวกนั้นมีไว้ให้เรียงแบบ string ได้
  // ลำดับเดียวกับเรียงแบบตัวเลข ไม่ได้มีไว้ให้คนอ่าน
  return String(Number.parseInt(match[2], 10));
}

/** วันของบิลจากเลขที่ (`YYYYMMDD`) — null เมื่อรูปแบบไม่ตรง */
export function orderNumberDay(orderNumber: string): string | null {
  return ORDER_NUMBER_PATTERN.exec(orderNumber)?.[1] ?? null;
}
