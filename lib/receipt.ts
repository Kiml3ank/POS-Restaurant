import type { Currency } from "@/lib/generated/prisma/enums";
import type { ReceiptKind } from "@/lib/generated/prisma/enums";

/**
 * ใบเสร็จ / ใบกำกับภาษีอย่างย่อ — ส่วนที่ไม่แตะฐานข้อมูล (บทที่ 12)
 *
 * **ไม่มี `import "server-only"`** เพราะหน้าใบเสร็จเป็น component ที่ client
 * ก็ต้องใช้ตอนแสดงหัวเอกสารและเลขที่ — เหมือน lib/money.ts และ lib/order-status.ts
 *
 * ⚠ เนื้อหาภาษีในไฟล์นี้ไม่ใช่คำแนะนำทางกฎหมาย ต้องให้ผู้สอบบัญชี/สรรพากร
 * ตรวจก่อนใช้งานจริง โดยเฉพาะถ้อยคำบนหัวเอกสารและรายการที่กฎหมายบังคับให้มี
 */

/** ชุดเอกสารของใบเสร็จ — ค่าเดียวในก้อนนี้ แยกเป็นค่าคงที่เพื่อไม่ให้พิมพ์ "ABB" กระจาย */
export const RECEIPT_SERIES = "ABB";

/**
 * จำนวนหลักของเลขลำดับ — 8 หลักคือ 99,999,999 ใบต่อสาขา
 *
 * เลขที่ **ไม่รีเซ็ตตลอดกาล** (ตกลงกับผู้ใช้แล้ว) จึงต้องเลือกให้ยาวพอที่จะไม่มีวัน
 * ต้องเปลี่ยนรูปแบบกลางคัน — การเปลี่ยนความยาวทีหลังทำให้เลขเก่ากับเลขใหม่
 * เรียงตามตัวอักษรไม่ตรงกับเรียงตามลำดับ ซึ่งพังทุกที่ที่มีคน sort เป็น string
 */
const SEQ_DIGITS = 8;

/**
 * ประกอบเลขที่เอกสารที่พิมพ์ลงใบจริง เช่น `HQ-00000123`
 *
 * เก็บผลลัพธ์ลงคอลัมน์ `Receipt.number` ด้วย ไม่ได้ประกอบสดตอนแสดงผลทุกครั้ง
 * เพราะลูกค้าที่โทรมาถามจะอ่าน "เลขบนใบ" ให้ฟัง — ต้องค้นด้วยสตริงนั้นได้ตรง ๆ
 */
export function formatReceiptNumber(branchCode: string, seq: number): string {
  return `${branchCode}-${String(seq).padStart(SEQ_DIGITS, "0")}`;
}

/**
 * ชนิดเอกสารที่ต้องออกให้สาขาที่ใช้สกุลเงินนี้
 *
 * ใบกำกับภาษีอย่างย่อเป็นเอกสารตามประมวลรัษฎากร **ของไทยเท่านั้น** สาขาที่ลาว
 * หรือเวียดนามออกเอกสารที่มีคำว่า "ใบกำกับภาษี" กับเลขผู้เสียภาษีไทยไม่ได้
 * — ผูกกับสกุลเงินเพราะนั่นคือสิ่งที่ระบบรู้จริงเกี่ยวกับประเทศของสาขา
 *
 * ผลลัพธ์ถูก **snapshot ลงแถว Receipt ตอนออกใบ** ไม่ได้เรียกซ้ำตอน render
 * (ดูเหตุผลใน schema.prisma ที่ enum ReceiptKind)
 */
export function receiptKindForCurrency(currency: Currency): ReceiptKind {
  return currency === "THB" ? "TAX_ABB" : "RECEIPT";
}

/** ถ้อยคำบนหัวเอกสาร — ต่างกันตามชนิด ไม่ใช่ตามสกุลเงิน (ชนิดถูก snapshot ไว้แล้ว) */
export const RECEIPT_KIND_TITLE: Record<ReceiptKind, string> = {
  TAX_ABB: "ใบเสร็จรับเงิน / ใบกำกับภาษีอย่างย่อ",
  RECEIPT: "ใบเสร็จรับเงิน",
};

