/**
 * เห็นหน้าแรกของหลังร้านที่เป็นสรุปยอดขาย (`/admin`) ไหม — spec §1
 *
 * OWNER/MANAGER เท่านั้น เพราะหน้านี้บอกยอดขายทั้งสาขาของวันนี้ในหน้าจอเดียว
 * ซึ่งเป็นข้อมูลระดับเดียวกับลิสต์ใบเสร็จย้อนหลัง (`canBrowseReceipts`)
 *
 * **ตำแหน่งอื่นไม่ได้ถูกกันออกจากจอหลังร้าน** — แค่ถูกพาไปที่ `/admin/menu` แทน
 * ซึ่งเป็นหน้าที่พวกเขาเข้ามาทำจริง (กด "ของหมด" กลางกะ) ไม่ใช่หน้าที่ขึ้นว่า
 * "คุณไม่มีสิทธิ์" แล้วจบ — ปุ่มที่พาไปหน้าที่ทำอะไรไม่ได้ แย่กว่าไม่มีปุ่ม
 */
export function canViewDashboard(role: StaffRole): boolean {
  return role === "OWNER" || role === "MANAGER";
}
