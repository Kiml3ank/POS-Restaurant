import type { StaffRole } from "@/lib/generated/prisma/enums";

/**
 * สิทธิ์ตามตำแหน่ง (ฐานของบทที่ 13 — ดึงมาทำก่อนเท่าที่ POS บทที่ 9 ต้องใช้)
 *
 * เก็บเป็นตารางกลางไฟล์เดียว ไม่กระจายเงื่อนไข `role === "OWNER"` ไว้ทั่วโค้ด
 * เพราะเวลาร้านขอเพิ่มตำแหน่งใหม่ จะได้แก้ที่เดียวจบ
 *
 * ไม่มี `import "server-only"` เพราะหน้าจอต้องใช้ตัดสินว่าจะโชว์ปุ่มไหน —
 * แต่ **การซ่อนปุ่มไม่ใช่การกันสิทธิ์** ทุก Server Action ต้องเช็คซ้ำฝั่ง server เสมอ
 */

export const STAFF_ROLE_LABEL: Record<StaffRole, string> = {
  OWNER: "เจ้าของร้าน",
  MANAGER: "ผู้จัดการ",
  CASHIER: "แคชเชียร์",
  SERVER: "พนักงานเสิร์ฟ",
  KITCHEN: "ครัว",
};

/** หน้าจอที่มีการจำกัดสิทธิ์ */
export type StaffScreen = "pos" | "kds" | "admin";

const SCREEN_ROLES: Record<StaffScreen, readonly StaffRole[]> = {
  // ครัวไม่ต้องเข้าหน้า POS เพราะไม่ได้รับเงินและไม่ได้เปิดโต๊ะ
  pos: ["OWNER", "MANAGER", "CASHIER", "SERVER"],
  /**
   * จอครัว (บทที่ 8) — แคชเชียร์ไม่ต้องเข้า เพราะจอครัวเปลี่ยนสถานะอาหารได้
   * และคนที่ถือเงินไม่ควรเป็นคนกดว่าอาหารเสร็จแล้วด้วย (แยกหน้าที่กันไว้ก่อน
   * ตามหลักเดียวกับที่บทที่ 13 จะใช้ทั้งบท)
   *
   * พนักงานเสิร์ฟเข้าได้ เพราะจอครัวคือที่ที่เห็นว่า "ของโต๊ะไหนพร้อมยกแล้ว"
   * และปุ่มเสิร์ฟแล้วอยู่บนจอนี้ — แต่ปุ่มของครัว (รับออร์เดอร์/ทำเสร็จ) เสิร์ฟกดไม่ได้
   */
  kds: ["OWNER", "MANAGER", "KITCHEN", "SERVER"],
  /**
   * หลังร้าน (โมดูล 04) — **ทุกตำแหน่งเข้าได้** ซึ่งต่างจากอีกสองจอโดยตั้งใจ
   *
   * เพราะสิ่งที่ทุกคนต้องทำได้บนจอนี้คือกด "ของหมด" ซึ่งเกิดกลางกะเสมอ และคนที่
   * รู้ก่อนคือคนที่ยืนอยู่ในร้าน ไม่ใช่เจ้าของที่อยู่บ้าน — ถ้าต้องโทรตามผู้จัดการ
   * มาปิดเมนูหนึ่งตัว สุดท้ายร้านจะไม่ปิด แล้วลูกค้าจะสั่งของที่ไม่มี
   *
   * ครัวเข้าจอนี้ได้ทั้งที่เข้า POS ไม่ได้ เพราะครัวเห็นตู้เย็นก่อนใคร —
   * คนละเรื่องกับเหตุผลที่กันครัวออกจาก POS (ไม่ได้รับเงิน ไม่ได้เปิดโต๊ะ)
   *
   * **"เข้าจอได้" ไม่เท่ากับ "แก้เมนูได้"** — ตัวคุมของจริงคือ canEditMenu()
   */
  admin: ["OWNER", "MANAGER", "CASHIER", "SERVER", "KITCHEN"],
};

export function canAccessScreen(role: StaffRole, screen: StaffScreen): boolean {
  return SCREEN_ROLES[screen].includes(role);
}

/**
 * การยกเลิกรายการที่ครัวเริ่มทำแล้ว = ของถูกทิ้งจริง มีต้นทุนจริง
 * จึงจำกัดไว้ที่ระดับหัวหน้าขึ้นไป และต้องกรอกเหตุผลเสมอ (เคสโกงในบทที่ 13)
 */
export function canCancelOrderItem(role: StaffRole): boolean {
  return role === "OWNER" || role === "MANAGER" || role === "CASHIER";
}

/**
 * กดปุ่มของครัวได้ไหม (รับออร์เดอร์ / ทำเสร็จแล้ว) — บทที่ 8
 *
 * แยกจาก canAccessScreen(role, "kds") โดยตั้งใจ เพราะ "เห็นจอ" กับ "กดปุ่มบนจอ"
 * ไม่ใช่สิทธิ์เดียวกัน: พนักงานเสิร์ฟต้องเห็นจอครัวเพื่อรู้ว่าของโต๊ะไหนพร้อมยก
 * แต่ต้องกดแทนครัวว่า "ทำเสร็จแล้ว" ไม่ได้ ไม่งั้นเวลาที่เก็บไว้วัดครัวในบทที่ 15
 * จะไม่ใช่เวลาที่ครัวทำจริง
 */
export function canCookOrderItem(role: StaffRole): boolean {
  return role === "OWNER" || role === "MANAGER" || role === "KITCHEN";
}

/**
 * กด "ยกไปเสิร์ฟแล้ว" (READY → SERVED) ได้ไหม — บทที่ 8
 *
 * ครัวกดไม่ได้เพราะครัวไม่ใช่คนยกไปวางบนโต๊ะ ถ้าให้ครัวกดได้ ตัวเลข
 * "ของพร้อมเสิร์ฟค้างอยู่กี่จาน" บนผังโต๊ะจะเป็นศูนย์ตลอดเวลา แล้วพนักงานเสิร์ฟ
 * จะไม่มีทางรู้ว่ามีของรออยู่ที่ช่องรับอาหาร
 */
export function canServeOrderItem(role: StaffRole): boolean {
  return role === "OWNER" || role === "MANAGER" || role === "CASHIER" || role === "SERVER";
}

/**
 * รับเงินปิดบิลได้ไหม — บทที่ 11
 *
 * ชุดเดียวกับ canCancelOrderItem() ด้วยเหตุผลเดียวกัน: **แตะเงิน**
 * พนักงานเสิร์ฟกดไม่ได้เพราะคนถือเงินกับคนเสิร์ฟต้องแยกกัน (แยกหน้าที่ตามหลัก
 * ที่บทที่ 13 ใช้ทั้งบท) — เสิร์ฟที่กดปิดบิลเองได้ คือเสิร์ฟที่รับเงินสดจากลูกค้า
 * แล้วปิดบิลเองได้โดยไม่มีคนที่สองรู้เห็น
 *
 * ครัวก็กดไม่ได้ และไม่ต้องมีข้อยกเว้นเพราะครัวเข้าหน้า POS ไม่ได้อยู่แล้ว
 */
export function canTakePayment(role: StaffRole): boolean {
  return role === "OWNER" || role === "MANAGER" || role === "CASHIER";
}

/**
 * สร้าง / แก้ / ลบ เมนู หมวด และกลุ่มตัวเลือก (โมดูล 04)
 *
 * จำกัดไว้ที่ระดับหัวหน้า เพราะ **การแก้ราคาคือการเปลี่ยนสิ่งที่ลูกค้าต้องจ่าย**
 * และเป็นช่องโกงที่ตรวจยากที่สุดอันหนึ่ง: ขึ้นราคาชั่วคราวตอนเก็บเงินแล้วลดกลับ
 * ทันทีหลังจากนั้น ถ้าไม่มี AuditLog เก็บค่าก่อน-หลังไว้ จะไม่มีใครย้อนดูได้เลย
 * (เคสที่เล่มยกไว้ในบทที่ 13) — ตัวเขียน log อยู่ใน lib/server/menu-admin.ts
 */
export function canEditMenu(role: StaffRole): boolean {
  return role === "OWNER" || role === "MANAGER";
}

/**
 * กด "ของหมด / มีของ" ได้ไหม — ทุกคนที่เข้าจอหลังร้านได้ กดได้
 *
 * แยกเป็นฟังก์ชันของตัวเองแทนที่จะเรียก canAccessScreen ตรง ๆ ที่จุดใช้งาน
 * เพราะสองอย่างนี้บังเอิญตรงกัน "ตอนนี้" ไม่ใช่ตรงกันโดยนิยาม — วันที่ร้านขอให้
 * เฉพาะหัวหน้ากดของหมดได้ จะได้แก้ที่นี่ที่เดียวโดยไม่ต้องไล่หาว่าที่ไหนบ้าง
 * ที่เขียน canAccessScreen(role, "admin") ไว้ด้วยความหมายว่า "กดของหมดได้"
 */
export function canToggleMenuAvailability(role: StaffRole): boolean {
  return canAccessScreen(role, "admin");
}
