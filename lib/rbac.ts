/**
 * ตำแหน่งไหน "ตั้ง/แก้" ตำแหน่งไหนได้บ้าง — กันการยกระดับสิทธิ์ตัวเอง
 *
 * ── ปัญหาที่ฟังก์ชันนี้ปิด ────────────────────────────────────────────────
 * ถ้าผู้จัดการสร้างบัญชีตำแหน่ง OWNER ได้ ผู้จัดการก็มีสิทธิ์ของเจ้าของร้าน
 * ได้ทันทีโดยไม่ต้องขออนุญาตใคร — แค่สร้างบัญชีใหม่แล้วใส่ PIN ที่ตัวเองรู้
 * เท่ากับสิทธิ์ทั้งหมดในไฟล์นี้ไม่มีความหมายเลย เพราะข้ามได้ในสองคลิก
 *
 * กติกา: **แก้ได้เฉพาะตำแหน่งที่ "ต่ำกว่า" ตัวเอง** เจ้าของร้านจึงเป็นคนเดียว
 * ที่ตั้งผู้จัดการได้ และไม่มีใครตั้ง OWNER เพิ่มได้นอกจาก OWNER
 *
 * ตารางลำดับชั้นอยู่ที่นี่ที่เดียว **ห้ามเขียน `role === "OWNER"` กระจายไว้ในหน้าจอ**
 */
const ROLE_RANK: Record<StaffRole, number> = {
  OWNER: 4,
  MANAGER: 3,
  CASHIER: 2,
  SERVER: 1,
  KITCHEN: 1,
};

export function canAssignRole(actorRole: StaffRole, targetRole: StaffRole): boolean {
  if (actorRole === "OWNER") {
    return true;
  }

  return canManageStaff(actorRole) && ROLE_RANK[targetRole] < ROLE_RANK[actorRole];
}

/**
 * แก้ไข/รีเซ็ต PIN ของพนักงานคนนี้ได้ไหม
 *
 * ใช้กติกาเดียวกับ `canAssignRole()` โดยดูจาก **ตำแหน่งปัจจุบันของเป้าหมาย** —
 * ผู้จัดการรีเซ็ต PIN ของเจ้าของร้านไม่ได้ (ไม่งั้นเข้าบัญชีเจ้าของได้ทันที)
 * แต่รีเซ็ตของแคชเชียร์ที่ลืม PIN กลางกะได้เอง ซึ่งเป็นงานประจำวันจริง
 */
export function canManageStaffMember(actorRole: StaffRole, targetRole: StaffRole): boolean {
  return canAssignRole(actorRole, targetRole);
}

